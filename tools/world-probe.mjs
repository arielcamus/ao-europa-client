import { chromium } from '@playwright/test';
const b = await chromium.launch({ channel: 'chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1024, height: 768 } });
p.on('pageerror', e => console.log('pageerror', e.message)); p.on('console', m => { if (m.type()==='error') console.log('console', m.text()); });
p.on('websocket', ws => { ws.on('framereceived', f => { const b = Buffer.from(f.payload); console.log('s2c', b.readUInt16LE(2), b.length, b.toString('hex').slice(0,120)); }); ws.on('framesent', f => { const b = Buffer.from(f.payload); console.log('c2s', b.readUInt16LE(2)); }); ws.on('close', () => console.log('ws close')); });
await p.goto('http://127.0.0.1:5785/');
await p.locator('#email').fill('aotest@local.test'); await p.locator('#password').fill('aotestpw1'); await p.locator('#connect').click();
await p.locator('#connect-stage[data-screen="account"]').waitFor({ timeout: 60000 }); await p.waitForTimeout(1500);
await p.mouse.click(247, 291); await p.waitForTimeout(600); await p.mouse.click(686, 729);
await p.waitForTimeout(8000);
console.log(await p.locator('#connection').innerText(), '|', await p.locator('#error').innerText(), '|', (await p.locator('#messages').innerText()).slice(-300));
await p.screenshot({ path: 'artifacts/screenshots/world-probe.png' });
await b.close();
