#!/usr/bin/env node
// Generates docs/COMPLETION.md (the single "what is left for a 100% feature-complete client" checklist) and docs/PLAYTHROUGH.md.
//   node tools/completion/build.mjs            write both files
//   node tools/completion/build.mjs --check    exit 1 when either is stale
// Inputs: docs/coverage.json (packets and forms, pre-HOO pinned; run tools/coverage/build-map.mjs first),
// tools/completion/data.json (behaviour items from the open issues, in-flight marks, gaps, work packages),
// tools/completion/playthrough.json (every player action with the expected result from the pinned server code).
// When an item lands: edit the json (delete the line or change a status), re-run, commit all.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs', 'COMPLETION.md');
const OUT_PT = join(ROOT, 'docs', 'PLAYTHROUGH.md');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function ptStats(pt) {
  const steps = pt.categories.flatMap((c) => c.steps);
  const n = (f) => steps.filter(f).length;
  return { total: steps.length, passing: n((s) => s.status.startsWith('passing')), failing: n((s) => s.status === 'failing'), blocked: n((s) => s.status === 'blocked'), recorded: n((s) => s.status === 'recorded'), inFlight: n((s) => s.status === 'in flight'), auto: n((s) => s.mode === 'auto'), manual: n((s) => s.mode === 'manual') };
}

export function renderPlaythrough(pt) {
  const st = ptStats(pt);
  const L = ['# End-to-end playthrough: what a player does and what the server must answer', ''];
  L.push('<!-- Generated by tools/completion/build.mjs from tools/completion/playthrough.json. Do not edit by hand. -->', '');
  L.push('Part of [COMPLETION.md](COMPLETION.md) (check 4). Every step has the EXPECTED RESULT derived from the pinned pre-HOO VB6 server (`tools/provenance/sources.lock.json`), with the VB6 function that decides it. `auto` = a recorder or Playwright scenario against the real server can drive and assert it (setup through GM commands, a DB UPDATE on a logged-out test char, or two bridge sessions); `manual` = needs a human, an NPC or data the server does not have.', '');
  L.push('Status: `untested` (no scenario yet), `recorded` (a real-server recording of the packets is on main, see `how`), `in flight` (a PR or branch covers it), `passing` (the end-to-end scenario passed against the real server), `failing` (the harness ran it and the server or client did not give the expected result) and `blocked` (the harness could not assert it, the reason is in the report). The last three come from `tools/completion/playthrough-report.json`, written by `pnpm playthrough` (WP-D, `tools/playthrough/`).', '');
  L.push(`**${st.total} steps: ${st.passing} passing end to end, ${st.failing} failing, ${st.blocked} blocked, ${st.recorded} recorded at protocol level, ${st.inFlight} in flight; ${st.auto} automatable, ${st.manual} manual.**`, '');
  L.push('| Category | Steps | Passing | Failing | Blocked | Recorded | In flight | Auto | Manual |', '|---|---|---|---|---|---|---|---|---|');
  for (const c of pt.categories) {
    const s = ptStats({ categories: [c] });
    L.push(`| [${c.title}](#${c.id}) | ${s.total} | ${s.passing} | ${s.failing} | ${s.blocked} | ${s.recorded} | ${s.inFlight} | ${s.auto} | ${s.manual} |`);
  }
  L.push('');
  for (const c of pt.categories) {
    L.push(`<a id="${c.id}"></a>`, `## ${c.title}`, '');
    L.push('| Id | Step | Expected result (pinned server) | Source | Mode | Status | How |', '|---|---|---|---|---|---|---|');
    for (const s of c.steps) L.push(`| ${s.id} | ${esc(s.step)} | ${esc(s.expected)} | ${esc(s.source)} | ${s.mode} | ${s.status} | ${esc(s.how)} |`);
    L.push('');
  }
  return L.join('\n');
}

export function render(cov, data, pt) {
  const fl = data.inFlight;
  const L = [];
  const packets = cov.packets;
  const missingPackets = packets.filter((p) => !p.covered);
  const pOk = packets.length - missingPackets.length;
  const forms = cov.forms;
  const full = forms.filter((f) => f.covered);
  const partial = forms.filter((f) => !f.covered && f.partial);
  const classA = forms.filter((f) => !f.covered && !f.partial && f.missing?.class === 'a');
  const screensY = full.length + partial.length + classA.length;
  const gaps = data.formGaps;
  const gapsCovered = gaps.filter((g) => full.some((f) => f.name === g.form));
  const screensX = full.length - gapsCovered.length;
  const beh = data.behaviour;
  const behOpen = beh.filter((b) => !b.inFlight && !b.blocked);
  const behFlight = beh.filter((b) => b.inFlight);
  const behBlocked = beh.filter((b) => b.blocked && !b.inFlight);
  const st = ptStats(pt);

  L.push('# Completion checklist: the classic client at 100%', '');
  L.push('<!-- Generated by tools/completion/build.mjs from docs/coverage.json and tools/completion/*.json. Do not edit by hand. -->', '');
  L.push('**Definition of 100% (Ariel, 21 Nov: "first the client 100% feature complete, then new content").** Four checks, all verifiable, all pre-HOO (no HOO data, assets or code):', '');
  L.push('1. Every packet of the pinned pre-HOO server and client has a codec and is handled.');
  L.push('2. Every form a player can open in the pinned VB6 client has a screen with every control (classes a/b/c/d below).');
  L.push('3. No open behaviour item: every open issue in arielcamus/ao-client is closed and the reported bugs are fixed.');
  L.push('4. The end-to-end playthrough ([PLAYTHROUGH.md](PLAYTHROUGH.md)) passes against the real server, every step.', '');
  L.push('## Totals', '');
  L.push('| Check | Done | Of | Left |', '|---|---|---|---|');
  L.push(`| Packets with a codec | ${pOk} | ${packets.length} | ${missingPackets.length} |`);
  L.push(`| Screens complete (all controls) | ${screensX} | ${screensY} | ${screensY - screensX} (${partial.length} partial, ${classA.length} not started, ${gapsCovered.length} covered but missing controls) |`);
  L.push(`| Behaviour items | 0 | ${beh.length} | **${beh.length} open** (${behOpen.length} to do, ${behFlight.length} in flight, ${behBlocked.length} blocked on data or a decision) |`);
  L.push(`| Playthrough steps passing end to end | ${st.passing} | ${st.total} | ${st.total - st.passing} (${st.recorded} recorded at protocol level on main, ${st.inFlight} in flight, ${st.auto} automatable, ${st.manual} manual) |`, '');
  L.push('Scope. Packets: the 8 post-pin packets are excluded (docs/COVERAGE.md "post-pin"); "codec" is a registered `[Table.Name]` entry, and the handling check is a name search in apps/web and the bridge. Screens: covered + partial + class a; classes b (account server), c (AO20 extras) and d (dead forms) are out. Playthrough: "passing" means an end-to-end run against the real server; none exists yet (WP-D).', '');
  L.push(`In flight now: ${Object.entries(fl.prs).map(([n, t]) => `PR #${n} (${t})`).join('; ')}; branches ${fl.branches.map((b) => '`' + b + '`').join(', ')} (no commits yet). Items marked **in flight** are not for new agents.`, '');

  L.push('## 1. Packets', '');
  L.push(`**${pOk} of ${packets.length} have a codec** (server to client ${cov.headline.s2cCovered}/${cov.headline.s2c}, client to server ${cov.headline.c2sCovered}/${cov.headline.c2s}); ${cov.headline.fixturePackets} have a recorded VB6 fixture.`, '');
  L.push('### Missing codecs', '');
  for (const p of missingPackets) L.push(`- [ ] \`${p.key}\` ${p.name} (${p.handler || p.writer || ''}). ${data.packetNotes?.[p.key] || ''}`);
  if (!missingPackets.length) L.push('None.');
  L.push('', '### Codec exists, handling not confirmed', '', 'Server packets whose name never appears in apps/web or the bridge (name search: a handler registered by number shows here by mistake). Each needs a one-line answer: handled where, or "VB6 ignores it too".', '');
  for (const p of data.unhandled || []) L.push(`- [ ] \`s2c:${p.id}\` ${p.name} (${p.group})`);
  if (!(data.unhandled || []).length) L.push('None.');
  L.push('');

  L.push('## 2. Screens', '');
  L.push(`**${screensX} of ${screensY}** player-facing forms are complete: ${full.length} have a surface (${gapsCovered.length} of them still miss controls), ${partial.length} partial, ${classA.length} not started. Out of scope: ${forms.filter((f) => f.missing?.class === 'b').length} class b, ${forms.filter((f) => f.missing?.class === 'c').length} class c, ${forms.filter((f) => f.missing?.class === 'd').length} class d.`, '');
  L.push('### Partial or not started', '');
  for (const f of [...partial, ...classA]) L.push(`- [ ] \`${f.name}\` ${f.purpose}.${fl.forms[f.name] ? ` **in flight (${fl.forms[f.name]})**` : ''} Missing: ${f.partialNote || f.missing?.note || 'see below'}`);
  L.push('', '### Covered forms that still miss controls', '');
  for (const g of gaps) L.push(`- [ ] \`${g.form}\` (${g.ref}): ${g.missing}`);
  L.push('', '### Out of scope (for the record)', '');
  for (const c of ['b', 'c', 'd']) L.push(`- class ${c}: ${forms.filter((f) => f.missing?.class === c).map((f) => f.name).join(', ')}`);
  L.push('');

  L.push('## 3. Behaviour: open issues and reported bugs', '');
  L.push(`**${beh.length} items** from the open issues (${[...new Set(beh.map((b) => b.issue).filter(Boolean))].sort((a, b) => b - a).map((i) => '#' + i).join(' ')}) and Ariel's reports. In flight: ${behFlight.length}; blocked on data or a decision: ${behBlocked.length}.`, '');
  const issues = [...new Set(beh.map((b) => b.issue))].sort((a, b) => (a || 1e9) - (b || 1e9));
  for (const i of issues) {
    L.push(`### ${i ? '#' + i : 'Reported by Ariel'}`, '');
    for (const b of beh.filter((x) => x.issue === i)) {
      const tags = [b.inFlight ? `**in flight (${b.inFlight})**` : '', b.blocked ? `blocked: ${b.blocked}` : '', b.label || ''].filter(Boolean).join(', ');
      L.push(`- [ ] ${b.text}${tags ? ` (${tags})` : ''}`);
    }
    L.push('');
  }

  L.push('## 4. End-to-end playthrough', '');
  L.push(`Full list with expected results and VB6 sources: [PLAYTHROUGH.md](PLAYTHROUGH.md). **${st.total} steps, ${st.passing} passing**, ${st.failing} failing, ${st.blocked} blocked, ${st.recorded} recorded, ${st.inFlight} in flight, ${st.auto} automatable, ${st.manual} manual.`, '');
  L.push('| Category | Steps | Recorded | In flight | Auto | Manual |', '|---|---|---|---|---|---|');
  for (const c of pt.categories) { const s = ptStats({ categories: [c] }); L.push(`| ${c.title} | ${s.total} | ${s.recorded} | ${s.inFlight} | ${s.auto} | ${s.manual} |`); }
  L.push('');
  L.push('## Work packages for parallel agents', '', 'Disjoint by files. Do not start anything marked in flight; rebase after #54 and #57 merge.', '');
  for (const w of data.workPackages) L.push(`- **${w.id} ${w.title}.** Files: ${w.files}. Closes: ${w.closes}.`);
  L.push('', '## Keeping this current', '', '`node tools/coverage/build-map.mjs && node tools/completion/build.mjs`. A test fails when these files are stale. Edit `tools/completion/data.json` or `playthrough.json` when an item lands, never the markdown.', '');
  return L.join('\n');
}

/** s2c packets whose VB6 name is never referenced in apps/web/src or packages/bridge/src. */
export function findUnhandled(cov) {
  const files = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name === 'node_modules' || e.name === 'dist') continue;
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p); else if (p.endsWith('.ts')) files.push(p);
    }
  };
  for (const d of ['apps/web/src', 'packages/bridge/src']) if (existsSync(join(ROOT, d))) walk(join(ROOT, d));
  const src = files.map((f) => readFileSync(f, 'utf8')).join('\n');
  return cov.packets.filter((p) => p.direction === 's2c' && !new RegExp(`\\b${p.name}\\b`).test(src)).map((p) => ({ id: p.id, name: p.name, group: p.group }));
}

export function load() {
  const j = (...p) => JSON.parse(readFileSync(join(ROOT, ...p), 'utf8'));
  const cov = j('docs', 'coverage.json');
  const data = j('tools', 'completion', 'data.json');
  data.unhandled = findUnhandled(cov);
  const pt = j('tools', 'completion', 'playthrough.json');
  // WP-D: the harness report (pnpm playthrough) overrides the hand-kept status of every step it ran.
  const reportFile = join(ROOT, 'tools', 'completion', 'playthrough-report.json');
  if (existsSync(reportFile)) {
    const results = JSON.parse(readFileSync(reportFile, 'utf8')).results;
    const byId = new Map(results.map((r) => [r.id, r]));
    // a partial run (AO_STEPS) merges into the report, so a step can be older than the newest run: say so (12 h tolerance, a full run takes hours)
    const newest = Math.max(0, ...results.map((r) => Date.parse(r.at ?? '') || 0));
    const staleNote = (r) => { const t = Date.parse(r.at ?? ''); if (!t) return 'stale (run date not recorded)'; return newest - t > 12 * 3600e3 ? `stale (from ${r.at.slice(0, 10)})` : ''; };
    for (const c of pt.categories) for (const s of c.steps) {
      const r = byId.get(s.id);
      if (!r) continue;
      // pass / fail always win; blocked only replaces 'untested' (a protocol-level 'recorded' or an 'in flight' PR stays visible)
      if (r.outcome === 'pass') s.status = r.manual ? 'passing (hand-merged)' : 'passing'; else if (r.outcome === 'fail') s.status = 'failing'; else if (s.status === 'untested') s.status = 'blocked';
      const tags = [r.at ? `run ${r.at.slice(0, 16).replace('T', ' ')}Z` : '', staleNote(r), r.note || ''].filter(Boolean).join(', ');
      s.how = `harness ${r.outcome}${tags ? ` (${tags})` : ''}: ${r.detail}`.slice(0, 400) + (s.how ? ` | before: ${s.how.slice(0, 120)}` : '');
    }
  }
  return { cov, data, pt };
}

export function outputs() {
  const { cov, data, pt } = load();
  return [[OUT, render(cov, data, pt) + '\n'], [OUT_PT, renderPlaythrough(pt) + '\n']];
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const outs = outputs();
  if (process.argv.includes('--check')) {
    const stale = outs.filter(([f, md]) => !existsSync(f) || readFileSync(f, 'utf8') !== md);
    if (stale.length) { console.error('stale: run node tools/completion/build.mjs'); process.exit(1); }
  } else for (const [f, md] of outs) { writeFileSync(f, md); console.log('wrote', f); }
}
