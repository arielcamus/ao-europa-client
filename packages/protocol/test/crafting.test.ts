import { readdirSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { NpcsServerPacketId as NS } from '../src/index.js';
import { CraftingClientPacketId as CC, CraftingServerPacketId as CS, decodeClientPacket, decodeServerPacket, encodeClientPacket, encodeServerPacket, ProtocolError } from '../src/index.js';

const bytes = (hex: string) => Uint8Array.from(Buffer.from(hex, 'hex'));
const hex = (value: Uint8Array) => Buffer.from(value).toString('hex');

// Hand-built from the VB6 writers' field order (server Protocol_Writes.bas, client Protocol_Writes.bas): id Int16 little endian, then the fields.
// ONLY packets no recording could produce: the generic crafting station (no NPC with Craftea exists in the shipped data), the special-fish
// fight, RomperCania (deletes an inventory slot) and list edge cases. Everything else is asserted against real VB6 recordings below.
const server: [string, string, object][] = [
  ['BlacksmithExtraObjects (empty list)', '46000000', { id: CS.BlacksmithExtraObjects, objects: [] }],
  ['CarpenterObjects (Byte count) with two objects', '4700' + '02' + 'c6000300', { id: CS.CarpenterObjects, objects: [198, 3] }],
  ['OpenCrafting', 'a80002', { id: CS.OpenCrafting, type: 2 }],
  ['CraftingItem (slot Byte, object Int16)', 'a90002ef10', { id: CS.CraftingItem, slot: 2, object: 4335 }],
  ['CraftingCatalyst', 'aa00' + '0802' + '0300' + '5a', { id: CS.CraftingCatalyst, object: 520, amount: 3, percent: 90 }],
  ['CraftingResult with an object: percent and price follow', 'ab00' + 'e803' + '46' + 'b80b0000', { id: CS.CraftingResult, object: 1000, percent: 70, price: 3000 }],
  ['CraftingResult 0 stops after the object', 'ab000000', { id: CS.CraftingResult, object: 0 }],
  ['PelearConPezEspecial', 'b000', { id: CS.PelearConPezEspecial }],
];
const client: [string, string, object][] = [
  ['AddItemCrafting with an explicit craft slot', '13010403', { id: CC.AddItemCrafting, inventorySlot: 4, craftSlot: 3 }],
  ['FinalizarPescaEspecial', '1e01', { id: CC.FinalizarPescaEspecial }],
  ['RomperCania', '1f01', { id: CC.RomperCania }],
];

describe('crafting packets with no recording: hex goldens from the VB6 writer order', () => {
  for (const [name, wire, packet] of server) {
    it(`server ${name}`, () => {
      expect(decodeServerPacket(bytes(wire))).toEqual(packet);
      expect(hex(encodeServerPacket(packet as never))).toBe(wire);
    });
  }
  for (const [name, wire, packet] of client) {
    it(`client ${name}`, () => {
      expect(decodeClientPacket(bytes(wire))).toEqual(packet);
      expect(hex(encodeClientPacket(packet as never))).toBe(wire);
    });
  }
  it('a list count larger than the frame is refused, never allocated', () => {
    expect(() => decodeServerPacket(bytes('4400ffff'))).toThrow(ProtocolError);
    expect(() => decodeServerPacket(bytes('4700ff'))).toThrow(ProtocolError);
  });
});

// Recordings of the real classic VB6 server (tests/fixtures/vb6/crafting). Never regenerated by tests.
const dir = new URL('../../../tests/fixtures/vb6/crafting/', import.meta.url);
interface Line { t_ms: number; dir: 'c2s' | 's2c'; id: number; name: string; hex: string }
const recordings = readdirSync(dir).filter(name => name.endsWith('.jsonl')).map(name => ({
  name, lines: readFileSync(new URL(name, dir), 'utf8').trim().split('\n').map(line => JSON.parse(line) as Line),
}));
const owned = { s2c: new Set<number>(Object.values(CS)), c2s: new Set<number>(Object.values(CC)) };
const file = (name: string) => recordings.find(r => r.name === `${name}.jsonl`)!.lines;
const decodeAll = (lines: Line[], side: Line['dir'], id: number) =>
  lines.filter(l => l.dir === side && l.id === id).map(l => (side === 's2c' ? decodeServerPacket : decodeClientPacket)(bytes(l.hex)) as Record<string, unknown>);
const objects = (lines: Line[], id: number) => decodeAll(lines, 's2c', id).map(p => p.objects as number[]);

describe('crafting packets against real VB6 recordings', () => {
  it('has every scenario', () => {
    expect(recordings.map(r => r.name.replace('.jsonl', '')).sort()).toEqual([
      'anvil-no-hammer', 'automated-action-refused', 'build-refused', 'carpenter-craft-walk-north', 'carpenter-craft-walk-south', 'chop-extraction', 'complete-action-none',
      'login', 'mine-extraction', 'mine-extraction-then-walk', 'smelt-extraction', 'smith-alchemy-tailor-build', 'smith-refused-carpenter-build', 'station-not-open',
    ]);
  });
  for (const recording of recordings) {
    it(`${recording.name}: every owned packet decodes and re-encodes to the same bytes`, () => {
      for (const line of recording.lines.filter(l => owned[l.dir].has(l.id))) {
        if (line.dir === 's2c') { const p = decodeServerPacket(bytes(line.hex)); expect('unknown' in p).toBe(false); expect(hex(encodeServerPacket(p as never))).toBe(line.hex); }
        else { const p = decodeClientPacket(bytes(line.hex)); expect('unknown' in p).toBe(false); expect(hex(encodeClientPacket(p as never))).toBe(line.hex); }
      }
    });
    it(`${recording.name}: logins are redacted`, () => {
      for (const line of recording.lines.filter(l => l.id === 304 || l.id === 305)) expect(line.hex).toHaveLength(4);
    });
  }
  it('smith: the anvil opens with weapons (33), armours (37) and runes (4) before ShowBlacksmithForm, in that order', () => {
    const lines = file('smith-alchemy-tailor-build'), at = lines.findIndex(l => l.id === CS.ShowBlacksmithForm);
    expect(lines.slice(at - 4, at + 1).map(l => l.id)).toEqual([37, CS.BlacksmithWeapons, CS.BlacksmithArmors, CS.BlacksmithExtraObjects, CS.ShowBlacksmithForm]);
    const [weapons] = objects(lines, CS.BlacksmithWeapons), [armors] = objects(lines, CS.BlacksmithArmors), [runes] = objects(lines, CS.BlacksmithExtraObjects);
    expect([weapons!.length, armors!.length, runes!.length]).toEqual([33, 37, 4]);
    expect(weapons!.slice(0, 3)).toEqual([3980, 165, 365]); expect(runes).toEqual([5170, 5171, 5172, 5173]);
  });
  it('carpenter: a Byte count (31) of objects, then ShowCarpenterForm', () => {
    const lines = file('smith-refused-carpenter-build'), at = lines.findIndex(l => l.id === CS.ShowCarpenterForm);
    expect(lines[at - 1]!.id).toBe(CS.CarpenterObjects);
    const [carpenter] = objects(lines, CS.CarpenterObjects);
    expect(carpenter!.length).toBe(31); expect(carpenter!.slice(0, 3)).toEqual([163, 479, 3466]);
    expect(lines[at - 1]!.hex.slice(4, 6)).toBe('1f'); // the count is one byte
  });
  it('alchemy and tailor: Int16-count lists (7 and 33), each followed by its Show*Form', () => {
    const lines = file('smith-alchemy-tailor-build');
    const [alchemy] = objects(lines, CS.AlquimistaObj), [tailor] = objects(lines, CS.SastreObj);
    expect([alchemy!.length, alchemy!.slice(0, 2), tailor!.length, tailor!.slice(0, 2)]).toEqual([7, [5997, 5996], 33, [3578, 30]]);
    expect(lines[lines.findIndex(l => l.id === CS.ShowAlquimiaForm) - 1]!.id).toBe(CS.AlquimistaObj);
    expect(lines[lines.findIndex(l => l.id === CS.ShowSastreForm) - 1]!.id).toBe(CS.SastreObj);
  });
  it('requests carry the values the scenarios sent', () => {
    const smith = file('smith-alchemy-tailor-build');
    expect(decodeAll(smith, 'c2s', CC.CraftBlacksmith)).toEqual([165, 365, 366, 367].map(object => ({ id: CC.CraftBlacksmith, object })));
    expect(decodeAll(smith, 'c2s', CC.CraftAlquimista)).toEqual([{ id: CC.CraftAlquimista, object: 5997 }]);
    expect(decodeAll(smith, 'c2s', CC.CraftSastre)).toEqual([{ id: CC.CraftSastre, object: 3578 }]);
    expect(decodeAll(file('carpenter-craft-walk-north'), 'c2s', CC.CraftCarpenter)).toEqual([{ id: CC.CraftCarpenter, object: 163, amount: 30 }]);
    expect(decodeAll(file('smith-refused-carpenter-build'), 'c2s', CC.CraftCarpenter)).toEqual([{ id: CC.CraftCarpenter, object: 163, amount: 2 }]);
    expect(decodeAll(file('complete-action-none'), 'c2s', CC.CompletarAccion)).toEqual([{ id: CC.CompletarAccion, action: 1 }]);
    expect(decodeAll(file('station-not-open'), 'c2s', CC.AddItemCrafting)).toEqual([{ id: CC.AddItemCrafting, inventorySlot: 4, craftSlot: 0 }]);
    expect(decodeAll(file('station-not-open'), 'c2s', CC.RemoveItemCrafting)).toEqual([{ id: CC.RemoveItemCrafting, craftSlot: 1, inventorySlot: 0 }]);
    expect(decodeAll(file('station-not-open'), 'c2s', CC.MoveCraftItem)).toEqual([{ id: CC.MoveCraftItem, drag: 1, drop: 2 }]);
    expect(decodeAll(file('station-not-open'), 'c2s', CC.AddCatalyst)).toEqual([{ id: CC.AddCatalyst, inventorySlot: 7 }]);
    for (const id of [CC.CraftItem, CC.CloseCrafting, CC.FlagTrabajar, CC.RepeatMacro]) expect(decodeAll(file('station-not-open'), 'c2s', id)).toEqual([{ id }]);
  });
  it('MacroTrabajoToggle: a refused build answers off, a carpenter build answers on, and the server turns it off itself when stopped', () => {
    const toggles = (name: string) => decodeAll(file(name), 's2c', CS.MacroTrabajoToggle).map(p => p.active);
    expect(toggles('smith-alchemy-tailor-build')).toEqual([false, false, false, false]);
    expect(toggles('smith-refused-carpenter-build')).toEqual([false, false, true, false]);
    expect(toggles('carpenter-craft-walk-north')).toEqual([true]);
    expect(toggles('carpenter-craft-walk-south')).toEqual([true, false]);
  });
  it('extraction: the tool asks for a target (WorkRequestTarget 19 mining, 26 smelting) and the click is StartAutomatedAction with no counter', () => {
    const sent = (name: string) => decodeAll(file(name), 'c2s', CC.StartAutomatedAction);
    expect(sent('mine-extraction')).toEqual([{ id: CC.StartAutomatedAction, x: 68, y: 63, skill: 19 }]);
    expect(sent('smelt-extraction')).toEqual([{ id: CC.StartAutomatedAction, x: 32, y: 62, skill: 26 }]);
    expect(sent('chop-extraction')).toEqual([{ id: CC.StartAutomatedAction, x: 38, y: 71, skill: 17 }]);
    expect(decodeAll(file('mine-extraction'), 's2c', 62).map(p => p.skill)).toEqual([19]);
    expect(decodeAll(file('smelt-extraction'), 's2c', 62).map(p => p.skill)).toEqual([26]);
    expect(file('mine-extraction').find(l => l.id === CC.StartAutomatedAction)!.hex).toBe('3401443f13'); // id + x + y + skill, nothing else
  });
  it('the work loop answers each extraction with ParticleFX, and FlagTrabajar alone does not stop it (the server keeps extracting)', () => {
    const lines = file('mine-extraction'), flag = lines.find(l => l.id === CC.FlagTrabajar)!;
    const effects = lines.filter(l => l.dir === 's2c' && l.id === 113);
    expect(effects.filter(l => l.t_ms < flag.t_ms).length).toBeGreaterThanOrEqual(3);
    expect(effects.filter(l => l.t_ms > flag.t_ms).length).toBeGreaterThanOrEqual(1);
  });
  it('refusals come as locale messages: no hammer at the anvil (1071) and no pending action (750)', () => {
    const locale = (name: string) => decodeAll(file(name), 's2c', NS.LocaleMsg).map(p => p.messageId);
    expect(locale('anvil-no-hammer')).toContain(1071);
    expect(locale('complete-action-none')).toContain(750);
  });
  it('a closed station answers nothing to its window packets: no crafting packet comes back', () => {
    const lines = file('station-not-open');
    expect(lines.filter(l => l.dir === 's2c' && owned.s2c.has(l.id))).toEqual([]);
    expect(lines.filter(l => l.dir === 'c2s').map(l => l.id)).toEqual([CC.AddItemCrafting, CC.RemoveItemCrafting, CC.AddCatalyst, CC.RemoveCatalyst, CC.MoveCraftItem, CC.CraftItem, CC.CloseCrafting, CC.FlagTrabajar, CC.RepeatMacro]);
  });
});
