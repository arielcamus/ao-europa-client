export interface GmCodec<T> { read(reader: Reader): T; write(writer: Writer, value: T): void }
const byte: GmCodec<number> = { read: r => r.readInt8(), write: (w, v) => { w.writeInt8(v); } };
const int16: GmCodec<number> = { read: r => r.readInt16(), write: (w, v) => { w.writeInt16(v); } };
const int32: GmCodec<number> = { read: r => r.readInt32(), write: (w, v) => { w.writeInt32(v); } };
const real32: GmCodec<number> = { read: r => r.readReal32(), write: (w, v) => { w.writeReal32(v); } };
const string: GmCodec<string> = { read: r => r.readString(), write: (w, v) => { w.writeString(v); } };
const bool: GmCodec<boolean> = { read: r => r.readBool(), write: (w, v) => { w.writeBool(v); } };
type Shape<S> = { [K in keyof S]: S[K] extends GmCodec<infer T> ? T : never };
function struct<const S extends Record<string, GmCodec<unknown>>>(fields: S): GmCodec<Shape<S>> {
  return {
    read(reader) {
      const value: Record<string, unknown> = {};
      for (const [key, codec] of Object.entries(fields)) value[key] = codec.read(reader);
      return value as Shape<S>;
    },
    write(writer, value) {
      for (const [key, codec] of Object.entries(fields)) codec.write(writer, (value as Record<string, unknown>)[key]);
    },
  };
}

/** SEPARATOR in the VB6 sources is vbNullChar: UserNameList and ShowSOSForm pack their rows into one string with it. */
export const GM_LIST_SEPARATOR = '\0';
/** ShowSOSForm rows are `name Ø query Ø type Ø date` (client HandleShowSOSForm: ReadField(n, row, Asc("Ø"))). */
export const GM_SOS_FIELD = '\u00d8';

/** WriteIPToNick: the four octets one Byte each, no length. */
const ipBytes: GmCodec<{ ip: number[] }> = {
  read: r => ({ ip: [r.readInt8(), r.readInt8(), r.readInt8(), r.readInt8()] }),
  write: (w, v) => { if (v.ip.length !== 4) throw new Error('IPToNick needs four octets'); for (const octet of v.ip) w.writeInt8(octet); },
};
/** e_DebugCommands: eGetLastLogs 0, eConnectionState 1 (the only one that carries a user name), eUserIdsState 2. */
const requestDebug: GmCodec<{ debugType: number; argument?: string }> = {
  read: r => { const debugType = r.readInt8(); return debugType === 1 ? { debugType, argument: r.readString() } : { debugType }; },
  write: (w, v) => { w.writeInt8(v.debugType); if (v.debugType === 1) w.writeString(v.argument ?? ''); },
};
/** WriteDebugLogResponse: a count then that many strings (empty ones are skipped by the client). */
const debugData: GmCodec<{ messages: string[] }> = {
  read: r => { const count = r.readInt16(), messages: string[] = []; for (let i = 0; i < count; i++) messages.push(r.readString()); return { messages }; },
  write: (w, v) => { w.writeInt16(v.messages.length); for (const message of v.messages) w.writeString(message); },
};

